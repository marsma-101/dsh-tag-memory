// 依据：《架构说明》§九、《流程_读取》§二、《功能说明》§十四「隔离」。
// 铁律：两道是「与」关系，不是「或」——G6/G7 专门抓 || 写错的实现。

import { test } from 'node:test'
import assert from 'node:assert/strict'

import { recall, checkIsolation } from '../../lib/engine/read.mjs'
import schema from '../../lib/engine/templates/schema.json' with { type: 'json' }
import scoring from '../../lib/engine/templates/scoring.json' with { type: 'json' }

const CONFIG = scoring
const EQ = { groups: [] }

function rec(over = {}) {
  return {
    编号: 'M-20261105-001',
    主要内容: '测试条目',
    形态: '技能',
    项目: 'P',
    智能体: 'A',
    自由标签: ['a', 'b'],
    稳定性: '观察',
    时距: 1,
    状态: '生效',
    ...over,
  }
}

function run(records, query) {
  return recall({
    records,
    query,
    identity: { bound: true, who: query['智能体'] },
    schema,
    config: CONFIG,
    equivalence: EQ,
  })
}

const idsOf = (res) => res.hits.map((h) => h['编号'])

/* ------------------------------------------------------------------ *
 * G1 跨项目查不到
 * ------------------------------------------------------------------ */
test('G1 跨项目：条目 项目=X，query 项目=Y → 查不到', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: 'X', 智能体: 'A' })]
  const res = run(records, { 项目: 'Y', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })

  assert.deepEqual(idsOf(res), [], '属于 X 项目的记忆，Y 项目必须查不到')
  assert.equal(res.filtered, 0, '硬筛后应为 0')
})

/* ------------------------------------------------------------------ *
 * G2 跨身份查不到
 * ------------------------------------------------------------------ */
test('G2 跨身份：条目 智能体=A，query 智能体=B → 查不到', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: 'P', 智能体: 'A' })]
  const res = run(records, { 项目: 'P', 智能体: 'B', 形态: '技能', 自由标签: ['a', 'b'] })

  assert.deepEqual(idsOf(res), [], '属于 A 身份的记忆，B 身份必须查不到')
  assert.equal(res.filtered, 0)
})

/* ------------------------------------------------------------------ *
 * G3 条目 项目=通用 → 任何项目可见
 * ------------------------------------------------------------------ */
test('G3 条目 项目=通用 → 任何项目都可见', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: '通用', 智能体: 'A', 自由标签: ['a', 'b'] })]

  for (const project of ['P', 'X', 'Y', '随便一个项目']) {
    const res = run(records, { 项目: project, 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })
    assert.deepEqual(idsOf(res), ['M-20261105-001'], `项目=通用 应对「${project}」可见`)
  }
})

/* ------------------------------------------------------------------ *
 * G4 条目 项目=引入 → 任何项目可见（与 G3 分开测，语义不同）
 * ------------------------------------------------------------------ */
test('G4 条目 项目=引入 → 任何项目都可见（与「通用」语义不同但可见性相同）', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: '引入', 智能体: 'A', 自由标签: ['a', 'b'] })]

  for (const project of ['P', 'X', 'Y']) {
    const res = run(records, { 项目: project, 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })
    assert.deepEqual(idsOf(res), ['M-20261105-001'], `项目=引入 应对「${project}」可见`)
  }
})

/* ------------------------------------------------------------------ *
 * G5 条目 智能体=通用 / =引入 → 任何身份可见
 * ------------------------------------------------------------------ */
test('G5 条目 智能体=通用 / =引入 → 任何身份都可见', () => {
  for (const agentValue of ['通用', '引入']) {
    const records = [rec({ 编号: 'M-20261105-001', 项目: 'P', 智能体: agentValue, 自由标签: ['a', 'b'] })]

    for (const agent of ['A', 'B', '任意身份']) {
      const res = run(records, { 项目: 'P', 智能体: agent, 形态: '技能', 自由标签: ['a', 'b'] })
      assert.deepEqual(
        idsOf(res),
        ['M-20261105-001'],
        `智能体=${agentValue} 应对身份「${agent}」可见`,
      )
    }
  }
})

/* ------------------------------------------------------------------ *
 * G6 【与关系】项目=通用 但 智能体=别人 → 查不到
 * ------------------------------------------------------------------ */
test('G6 【与关系】条目 项目=通用 但 智能体=别人 → 查不到（不得因项目放行就放行）', () => {
  const records = [
    rec({ 编号: 'M-20261105-001', 项目: '通用', 智能体: '别人', 自由标签: ['a', 'b'] }),
  ]
  const res = run(records, { 项目: 'P', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })

  assert.deepEqual(
    idsOf(res),
    [],
    '项目=通用 只满足项目维度，智能体=别人 不满足身份维度 → 两维度是「与」，必须查不到。' +
      '若返回则说明实现用了「或」（||）',
  )
  assert.equal(res.filtered, 0)
})

/* ------------------------------------------------------------------ *
 * G7 【与关系反向】智能体=通用 但 项目=别人 → 查不到
 * ------------------------------------------------------------------ */
test('G7 【与关系反向】条目 智能体=通用 但 项目=别人 → 查不到', () => {
  const records = [
    rec({ 编号: 'M-20261105-001', 项目: '别人项目', 智能体: '通用', 自由标签: ['a', 'b'] }),
  ]
  const res = run(records, { 项目: 'P', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })

  assert.deepEqual(idsOf(res), [], '智能体=通用 只满足身份维度，项目=别人 不满足 → 必须查不到')
  assert.equal(res.filtered, 0)
})

/* ------------------------------------------------------------------ *
 * G8 精确匹配，不做模糊
 * ------------------------------------------------------------------ */
test('G8 精确字符串匹配，不做模糊：X vs x / X 项目 都不匹配', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: 'X', 智能体: 'A', 自由标签: ['a', 'b'] })]

  for (const variant of ['x', 'X 项目', 'X项目', 'xx']) {
    const res = run(records, { 项目: variant, 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })
    assert.deepEqual(idsOf(res), [], `项目名必须精确匹配，「${variant}」不应匹配「X」`)
  }

  // 反证：精确值能查到
  const ok = run(records, { 项目: 'X', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })
  assert.deepEqual(idsOf(ok), ['M-20261105-001'])
})

/* ------------------------------------------------------------------ *
 * G9 query 项目=通用 → 按字面只能看到 通用+引入（Q7 裁定）
 * ------------------------------------------------------------------ */
test('G9 query 项目=通用（Q7）→ 按字面只看到 通用/引入 条目，看不到具体项目条目', () => {
  const records = [
    rec({ 编号: 'M-20261105-001', 项目: '通用', 智能体: 'A', 自由标签: ['a', 'b'] }),
    rec({ 编号: 'M-20261105-002', 项目: '引入', 智能体: 'A', 自由标签: ['a', 'b'] }),
    rec({ 编号: 'M-20261105-003', 项目: 'P', 智能体: 'A', 自由标签: ['a', 'b'] }),
  ]
  const res = run(records, { 项目: '通用', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })

  const got = idsOf(res).sort()
  assert.deepEqual(
    got,
    ['M-20261105-001', 'M-20261105-002'],
    `按字面：query 项目=通用 只能看到 通用/引入 条目，实际 ${got.join(',')}`,
  )
  assert.equal(res.filtered, 2, '「P」项目条目不应被看到（通用是白名单值，不是通配符）')
})

/* ------------------------------------------------------------------ *
 * G10 返回必须回显实际用的 项目/智能体
 * ------------------------------------------------------------------ */
test('G10 返回必须原样回显实际用的 项目/智能体（名字写歪要能当场发现）', () => {
  const records = [rec({ 编号: 'M-20261105-001', 项目: 'P', 智能体: 'A', 自由标签: ['a', 'b'] })]
  const query = { 项目: 'P', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] }
  const res = run(records, query)

  assert.equal(res.echo['项目'], query['项目'], `echo.项目 必须逐字等于入参，实际「${res.echo['项目']}」`)
  assert.equal(res.echo['智能体'], query['智能体'], `echo.智能体 必须逐字等于入参，实际「${res.echo['智能体']}」`)
  assert.equal(res.echo['形态'], query['形态'])
  assert.deepEqual(res.echo['自由标签'], query['自由标签'], 'echo 的自由标签也必须原样回显')
})

/* ------------------------------------------------------------------ *
 * G11 条目 项目/智能体 为空 → 按通用处理并标出来，不静默滤掉
 * ------------------------------------------------------------------ */
test('G11 条目 项目/智能体 为空 → 按通用处理且在返回里标出，不得静默滤掉', () => {
  const records = [
    rec({ 编号: 'M-20261105-001', 项目: '', 智能体: '', 自由标签: ['a', 'b'] }),
  ]
  const res = run(records, { 项目: 'P', 智能体: 'A', 形态: '技能', 自由标签: ['a', 'b'] })

  // 空值不是黑名单——不能静默消失
  assert.equal(res.filtered, 1, '空值条目必须过硬筛（按通用处理），不得被静默滤掉')
  assert.deepEqual(idsOf(res), ['M-20261105-001'], '空值条目应能返回')

  const hit = res.hits[0]
  assert.ok(Array.isArray(hit.blankFields), '返回里必须有 blankFields 标记')
  assert.ok(hit.blankFields.includes('项目'), `blankFields 必须标出「项目」为空，实际 ${JSON.stringify(hit.blankFields)}`)
  assert.ok(hit.blankFields.includes('智能体'), 'blankFields 必须标出「智能体」为空')
})

/* ------------------------------------------------------------------ *
 * G-附加 checkIsolation 单元级：与关系真值表
 * ------------------------------------------------------------------ */
test('G-附加 checkIsolation 真值表：6 种组合逐一验证「与」关系', () => {
  const cases = [
    { 项目: 'P', 智能体: 'A', expect: true, why: '两个维度都精确命中' },
    { 项目: '通用', 智能体: 'A', expect: true, why: '项目通用 + 身份命中' },
    { 项目: 'P', 智能体: '通用', expect: true, why: '项目命中 + 身份通用' },
    { 项目: '通用', 智能体: '通用', expect: true, why: '两个都通用' },
    { 项目: '引入', 智能体: '引入', expect: true, why: '两个都引入' },
    { 项目: '通用', 智能体: 'B', expect: false, why: '项目通用但身份不符 → 与关系失败' },
    { 项目: 'Q', 智能体: '通用', expect: false, why: '身份通用但项目不符 → 与关系失败' },
  ]

  for (const c of cases) {
    const { pass } = checkIsolation(rec({ 项目: c['项目'], 智能体: c['智能体'] }), { project: 'P', agent: 'A' }, schema)
    assert.equal(pass, c.expect, `项目=${c['项目']} 智能体=${c['智能体']}：${c.why}，期望 ${c.expect} 实际 ${pass}`)
  }
})
